//go:build ignore

// gen.go parses go.mod, extracts the github.com/SiaFoundation/s3d version,
// and writes build_gen.go. Run with: go run internal/build/gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	f, err := os.Open("go.mod")
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to open go.mod: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	s3dVersion := ""

	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if strings.HasPrefix(line, "github.com/SiaFoundation/s3d ") {
			parts := strings.Fields(line)
			if len(parts) >= 2 {
				s3dVersion = parts[1]
			}
			break
		}
	}

	if s3dVersion == "" {
		fmt.Fprintln(os.Stderr, "github.com/SiaFoundation/s3d not found in go.mod")
		os.Exit(1)
	}

	content := fmt.Sprintf(`package build

// Code generated by gen.go from go.mod. DO NOT EDIT.

// s3dVersion is the resolved version of github.com/SiaFoundation/s3d from go.mod.
const s3dVersion = %q
`, s3dVersion)

	if err := os.WriteFile("internal/build/build_gen.go", []byte(content), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write build_gen.go: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("wrote internal/build/build_gen.go (s3dVersion=%s)\n", s3dVersion)
}
